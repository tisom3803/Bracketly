# v3.3 searchable "Who are you?" picker: local only (server blocked), 128-player legacy + Pro-Am + Club Cup data
import asyncio, json, sys
from playwright.async_api import async_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8765/'
fails = []
def ok(c, msg):
    print(('PASS ' if c else 'FAIL ') + msg)
    if not c: fails.append(msg)
async def open_ds(b, name, w=390, h=844):
    data = json.load(open(f'/workspace/sweep/data-{name}.json'))
    ctx = await b.new_context(viewport={'width':w, 'height':h}, device_scale_factor=2, is_mobile=True, has_touch=True)
    await ctx.route('**/*supabase*', lambda r: r.abort()); pg = await ctx.new_page()
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    await pg.goto(URL, wait_until='networkidle')
    await pg.evaluate("d => { localStorage.clear(); Object.entries(d.ls).forEach(([k, v]) => localStorage.setItem(k, v)) }", data)
    await pg.goto(URL + '?join=' + data['code'], wait_until='networkidle'); await pg.wait_for_timeout(1000)
    return ctx, pg, errs
async def rows(pg): return await pg.eval_on_selector_all('.whor', "els => els.map(e => e.querySelector('b').textContent)")
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx, pg, errs = await open_ds(b, 'legacy')
        ok(await pg.query_selector('#whoq') is not None, 'gate shows the search box')
        n = await pg.evaluate("players().length"); r = await rows(pg)
        ok(len(r) == n and n >= 100, f'all {n} players listed vertically ({len(r)} rows)')
        ok(await pg.evaluate("document.documentElement.scrollWidth <= innerWidth && [...document.querySelectorAll('.whor')].every(e => e.getBoundingClientRect().right <= innerWidth)"), 'no horizontal scrolling at 390px')
        ok(await pg.evaluate("[...document.querySelectorAll('.whor')].every(e => e.getBoundingClientRect().height >= 44)"), 'rows are at least 44px tall')
        ok(await pg.evaluate("document.querySelectorAll('.whoh').length >= 10"), 'A-Z letter headers without teams')
        ok(await pg.is_visible('text=Continue as spectator') and 'Director' in (await pg.inner_text('#app')), 'spectator and Director options kept')
        await pg.click('#whoq'); await pg.keyboard.type('fernandez', delay=40); await pg.wait_for_timeout(400)
        r = await rows(pg)
        ok(len(r) > 0 and all('Fernández' in x for x in r), f'accent-insensitive last-name search "fernandez" -> {len(r)} rows, e.g. {r[:2]}')
        ok(await pg.evaluate("document.activeElement && document.activeElement.id === 'whoq'"), 'focus stays in the search box while typing')
        await pg.fill('#whoq', 'SEBASTIAN'); await pg.wait_for_timeout(400); r = await rows(pg)
        ok(len(r) > 0 and all(x.startswith('Sebastián') for x in r), f'case/accent-insensitive first name "SEBASTIAN" -> {len(r)}')
        await pg.fill('#whoq', 'anas o sui'); await pg.wait_for_timeout(400); r = await rows(pg)
        ok(len(r) >= 1 and all(x.startswith('Anastasia') and 'Súilleabháin' in x for x in r), f'first + last prefix "anas o sui" -> {r}')
        await pg.fill('#whoq', 'zzqx'); await pg.wait_for_timeout(400)
        ok(len(await rows(pg)) == 0 and 'No one' in (await pg.inner_text('#app')), 'no-match message')
        await pg.fill('#whoq', 'mcall'); await pg.wait_for_timeout(400)
        first = await pg.query_selector('.whor'); pid = await first.get_attribute('data-id'); await first.click(); await pg.wait_for_timeout(800)
        ok(await pg.evaluate(f"view.me === '{pid}'") and await pg.query_selector('#whoq') is None, 'tapping a row sets view.me and closes the gate')
        await pg.evaluate("view.modal = 'who'; render()"); await pg.wait_for_timeout(400)
        ok(await pg.query_selector('.modal #whoq, #whoq') is not None and await pg.query_selector('[aria-current="true"].whor') is not None, '"Who are you" modal has search and marks the current pick')
        await pg.fill('#whoq', 'smith'); await pg.wait_for_timeout(400); r = await rows(pg)
        ok(len(r) > 0 and all('Smith' in x for x in r), f'modal search works ({len(r)})')
        await pg.screenshot(path='/workspace/shots/v330-picker-legacy-modal.png')
        ok(not errs, f'no page errors {errs[:2]}'); await ctx.close()
        ctx, pg, errs = await open_ds(b, 'proam')
        hs = await pg.eval_on_selector_all('.whoh', 'els => els.map(e => e.textContent)')
        ok(any('Team' in h or 'team' in h for h in hs), f'Pro-Am grouped by team: {hs[:3]}')
        await pg.screenshot(path='/workspace/shots/v330-picker-proam-390.png')
        await pg.fill('#whoq', 'rafa'); await pg.wait_for_timeout(400); r = await rows(pg)
        ok(len(r) >= 1, f'Pro-Am search "rafa" -> {r[:3]}')
        await pg.screenshot(path='/workspace/shots/v330-picker-proam-search-390.png')
        ok(not errs, f'no page errors {errs[:2]}'); await ctx.close()
        ctx, pg, errs = await open_ds(b, 'cup')
        hs = await pg.eval_on_selector_all('.whoh', 'els => els.map(e => e.textContent)')
        ok(len(hs) >= 2, f'Club Cup grouped by club: {hs}')
        ok(not errs, f'no page errors {errs[:2]}'); await ctx.close()
        await b.close()
    print('RESULT', 'FAIL' if fails else 'PASS', len(fails))
    sys.exit(1 if fails else 0)
asyncio.run(main())
