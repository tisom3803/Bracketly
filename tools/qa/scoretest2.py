import asyncio, json, sys
from playwright.async_api import async_playwright
W = int(sys.argv[1]) if len(sys.argv) > 1 else 390
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); ctx = await b.new_context(viewport={'width':W,'height':844})
        await ctx.route('**/*supabase*', lambda r: r.abort())
        pg = await ctx.new_page(); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append('console:'+m.text) if m.type=='error' else None)
        await pg.goto('http://127.0.0.1:8765/', wait_until='networkidle')
        await pg.click('[data-act=sampleclassic]'); await pg.wait_for_timeout(1500)
        await pg.click('[data-act=pickme][data-id=__guest]'); await pg.wait_for_timeout(300)
        ids = await pg.evaluate("(() => { syncEngine(); return allMatches(true).filter(m => !state.results[m.id] && bothKnown(m) && getScoringFormatKey(m)==='tennis_bo3_mtb10').slice(0,5).map(m=>m.id) })()")
        mid, mid2, mid3 = ids[0], ids[1], ids[2]
        async def openm(i):
            await pg.evaluate(f"view.matchId='{i}'; view.modal='match'; view.sm=null; render()"); await pg.wait_for_timeout(250)
        await openm(mid)
        await pg.fill('#sc-0-0','6'); await pg.fill('#sc-0-1','5'); await pg.fill('#sc-1-0','6'); await pg.fill('#sc-1-1','2')
        await pg.click('[data-act=reviewscore]'); await pg.wait_for_timeout(200)
        print('1 err 6-5:', await pg.inner_text('.bk-note.err'))
        print('  override btn (guest):', await pg.locator('[data-act=reviewscore][data-v=loose]').count())
        await pg.fill('#sc-0-1','4'); await pg.wait_for_timeout(250)
        print('2 mtb disabled:', await pg.evaluate("document.getElementById('sc-2-0').disabled"), '|', await pg.locator('.bk-hint[role=status]').inner_text())
        print('  focus kept:', await pg.evaluate("document.activeElement && document.activeElement.id"))
        await pg.click('[data-act=reviewscore]'); await pg.wait_for_timeout(200)
        print('  review cols:', await pg.evaluate("document.querySelectorAll('.sc2 thead th').length"), await pg.inner_text('.sheet .st.warn'))
        await pg.click('[data-act=savescore]'); await pg.wait_for_timeout(300)
        rec = await pg.evaluate(f"Store.get('m:{mid}')"); print('  stored:', {k:rec.get(k) for k in ['w','s','hist','corrected']})
        await openm(mid)
        print('  view chip:', await pg.inner_text('.sheet p .st'), '| cols:', await pg.evaluate("document.querySelectorAll('.sc2 thead th').length"), '|', await pg.inner_text('.bk-attr'))
        await pg.click('[data-act=scoreedit]'); await pg.wait_for_timeout(200)
        await pg.fill('#sc-1-0','7'); await pg.fill('#sc-1-1','5'); await pg.click('[data-act=reviewscore]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act=savescore]'); await pg.wait_for_timeout(300)
        rec = await pg.evaluate(f"Store.get('m:{mid}')"); print('3 corrected:', rec.get('s'), rec.get('corrected'), len(rec.get('hist') or []))
        await openm(mid)
        print('  chip:', await pg.inner_text('.sheet p .st'), '| hist summary:', await pg.inner_text('.bk-disc summary'))
        # split sets, no MTB
        await openm(mid2)
        await pg.fill('#sc-0-0','6'); await pg.fill('#sc-0-1','4'); await pg.fill('#sc-1-0','4'); await pg.fill('#sc-1-1','6')
        await pg.click('[data-act=reviewscore]'); await pg.wait_for_timeout(200)
        print('4 split err:', await pg.inner_text('.bk-note.err'))
        await pg.fill('#sc-2-0','10'); await pg.fill('#sc-2-1','9'); await pg.click('[data-act=reviewscore]'); await pg.wait_for_timeout(200)
        print('  10-9 err:', await pg.inner_text('.bk-note.err'))
        # retirement
        await pg.click('[data-act=scmode][data-v=retire]'); await pg.wait_for_timeout(200)
        print('5 retire title:', await pg.inner_text('#sheet-h'), '| kept rows:', await pg.evaluate("[0,1,2].map(i=>document.getElementById('sc-'+i+'-0').value)"))
        await pg.fill('#sc-2-0','5'); await pg.fill('#sc-2-1','3')
        await pg.click('[data-act=retreview]'); await pg.wait_for_timeout(200)
        print('  no side err:', await pg.inner_text('.bk-note.err'))
        await pg.click('[data-act=retpick][data-v=team2]'); await pg.wait_for_timeout(200)
        print('  rows after pick:', await pg.evaluate("[0,1,2].map(i=>document.getElementById('sc-'+i+'-0').value)"))
        await pg.click('[data-act=retreview]'); await pg.wait_for_timeout(200)
        print('  review:', await pg.inner_text('.bk-note.warn'))
        await pg.click('[data-act=saveret]'); await pg.wait_for_timeout(300)
        rec = await pg.evaluate(f"Store.get('m:{mid2}')"); print('  stored:', {k:rec.get(k) for k in ['w','s','outcome','retired','note','txt']})
        await openm(mid2); print('  view:', await pg.inner_text('.sheet p:has(.st)'), '|', await pg.inner_text('.bk-attr'))
        # walkover
        await openm(mid3)
        await pg.click('[data-act=scmode][data-v=wo]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act=savewo][data-v=team1]'); await pg.wait_for_timeout(200)
        print('6 ask:', (await pg.inner_text('.modal.intro .sheet p'))[:80])
        await pg.click('[data-act=askyes]'); await pg.wait_for_timeout(300)
        rec = await pg.evaluate(f"Store.get('m:{mid3}')"); print('  stored:', {k:rec.get(k) for k in ['w','s','outcome','note']})
        # legacy records
        await pg.evaluate(f"Store.set('m:{ids[3]}', {{w:'team2', s:null, note:'Walkover or retired', by:'__guest', ts:Date.now()}}); Store.set('m:{ids[4]}', {{w:'team1', s:[[6,4],[6,3]], by:'__guest', ts:Date.now()}})")
        await openm(ids[3]); print('7 legacy wo:', await pg.inner_text('.sheet p:has(.st)'), '|', await pg.inner_text('.bk-attr'), '| table:', await pg.locator('.sc2').count())
        await openm(ids[4]); print('  legacy score:', await pg.inner_text('.sheet p:has(.st)'), '| cols:', await pg.evaluate("document.querySelectorAll('.sc2 thead th').length"), '| hist:', await pg.locator('.bk-disc').count())
        # director override
        await pg.evaluate("view.modal=null; view.tab='admin'; render()"); await pg.wait_for_timeout(200)
        await pg.fill('#pin','1234'); await pg.click('[data-act=unlock]'); await pg.wait_for_timeout(600)
        print('8 admin:', await pg.evaluate('view.admin'))
        ids2 = await pg.evaluate("(() => { syncEngine(); return allMatches(true).filter(m => !state.results[m.id] && bothKnown(m) && getScoringFormatKey(m)==='tennis_bo3_mtb10').slice(0,1).map(m=>m.id) })()")
        await openm(ids2[0]); await pg.fill('#sc-0-0','8'); await pg.fill('#sc-0-1','6'); await pg.fill('#sc-1-0','6'); await pg.fill('#sc-1-1','1')
        await pg.click('[data-act=reviewscore]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act=reviewscore][data-v=loose]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act=savescore]'); await pg.wait_for_timeout(300)
        rec = await pg.evaluate(f"Store.get('m:{ids2[0]}')"); print('  override stored:', rec.get('s'), rec.get('override'))
        # unit rules
        print('9 rules:', await pg.evaluate("""[[{kind:'set',to:6},7,6],[{kind:'set',to:6},6,5],[{kind:'set',to:8,pro:true},9,7],[{kind:'set',to:8,pro:true},8,7],[{kind:'race',to:11,what:'A game'},12,10],[{kind:'race',to:11,what:'A game'},12,9],[{kind:'race',to:10,what:'x'},10,8],[{kind:'race',to:15,what:'x'},15,14]].map(([r,a,b])=>a+'-'+b+':'+(rowProblem(r,a,b,'S')?'bad':'ok')).join(' ')"""))
        print('errors:', errs)
        await b.close()
asyncio.run(main())
